#!/usr/bin/env bash
#
# ==========================================================
# Zalo Wine Installer
# Setup Script
# Version : 4.0
# Author  : Long Nguyen
# ==========================================================

set -euo pipefail

##############################################################################
# Repository
##############################################################################

GITHUB_USER="longnguyen2026"
REPO_NAME="zalo-wine-v3"
BRANCH="main"

RAW_URL="https://raw.githubusercontent.com/${GITHUB_USER}/${REPO_NAME}/${BRANCH}"

##############################################################################
# Temporary Directory
##############################################################################

TMP_DIR="$(mktemp -d)"

cleanup() {
    rm -rf "$TMP_DIR"
}

trap cleanup EXIT

##############################################################################
# Colors
##############################################################################

GREEN='\033[0;32m'
RED='\033[0;31m'
BLUE='\033[1;34m'
CYAN='\033[1;36m'
NC='\033[0m'

##############################################################################
# Functions
##############################################################################

log() {
    echo -e "${GREEN}[INFO]${NC} $1"
}

error() {
    echo -e "${RED}[ERROR]${NC} $1"
}

##############################################################################
# Banner
##############################################################################

echo
echo -e "${BLUE}======================================================${NC}"
echo -e "${CYAN}        Zalo Wine Installer v4.0${NC}"
echo -e "${BLUE}======================================================${NC}"
echo

##############################################################################
# Download Installer
##############################################################################

log "Downloading installer..."

curl -fsSL \
    "$RAW_URL/install-zalo-v4.sh" \
    -o "$TMP_DIR/install-zalo-v4.sh"

chmod +x "$TMP_DIR/install-zalo-v3.sh"

##############################################################################
# Execute
##############################################################################

exec "$TMP_DIR/install-zalo-v4.sh"
